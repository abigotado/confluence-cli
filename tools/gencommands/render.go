package main

import (
	"fmt"
	"sort"
	"strings"

	"github.com/abigotado/confluence-cli/internal/cli"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const generatedNotice = "<!-- Code generated by tools/gencommands. DO NOT EDIT. -->"

type flagInfo struct {
	Name, Shorthand, Type, Default, Usage string
}

type commandInfo struct {
	Path, Short, Args string
	Flags             []flagInfo
}

type commandTree struct {
	Globals  []flagInfo
	Commands []commandInfo
}

func collect(root *cobra.Command) commandTree {
	var tree commandTree
	root.PersistentFlags().VisitAll(func(flag *pflag.Flag) {
		if !flag.Hidden {
			tree.Globals = append(tree.Globals, describeFlag(flag))
		}
	})
	var walk func(*cobra.Command)
	walk = func(command *cobra.Command) {
		for _, child := range command.Commands() {
			if child.Hidden || child.IsAdditionalHelpTopicCommand() || child.Name() == "help" || child.Name() == "completion" {
				continue
			}
			if child.HasSubCommands() {
				walk(child)
				continue
			}
			info := commandInfo{Path: child.CommandPath(), Short: child.Short}
			if _, args, found := strings.Cut(child.Use, " "); found {
				info.Args = args
			}
			inherited := child.InheritedFlags()
			child.LocalFlags().VisitAll(func(flag *pflag.Flag) {
				if !flag.Hidden && inherited.Lookup(flag.Name) == nil {
					info.Flags = append(info.Flags, describeFlag(flag))
				}
			})
			sort.Slice(info.Flags, func(i, j int) bool { return info.Flags[i].Name < info.Flags[j].Name })
			tree.Commands = append(tree.Commands, info)
		}
	}
	walk(root)
	sort.Slice(tree.Globals, func(i, j int) bool { return tree.Globals[i].Name < tree.Globals[j].Name })
	sort.Slice(tree.Commands, func(i, j int) bool { return tree.Commands[i].Path < tree.Commands[j].Path })
	return tree
}

func describeFlag(flag *pflag.Flag) flagInfo {
	defaultValue := flag.DefValue
	if defaultValue == "false" || defaultValue == "[]" {
		defaultValue = ""
	}
	return flagInfo{Name: flag.Name, Shorthand: flag.Shorthand, Type: flag.Value.Type(), Default: defaultValue, Usage: flag.Usage}
}

