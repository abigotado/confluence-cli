func flagLabel(flag flagInfo) string {
	if flag.Shorthand != "" {
		return fmt.Sprintf("`-%s, --%s`", flag.Shorthand, flag.Name)
	}
	return "`--" + flag.Name + "`"
}

func code(value string) string {
	if value == "" {
		return ""
	}
	return "`" + value + "`"
}

func rootCommand() *cobra.Command {
	return cli.NewApp().NewRootCommand()
}
